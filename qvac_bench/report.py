"""Render saved results as RESULTS.md. Every number comes from files under results/."""
import json
from pathlib import Path

from . import ROOT

CATEGORIES = ["single", "selection", "args", "no_tool", "parallel", "forced", "multi_turn", "deferred"]


def _toolcall_section(results: Path) -> list[str]:
    runs = sorted((results / "toolcalls").glob("*/summary.json"))
    if not runs:
        return ["## Tool-call conformance", "", "No model runs recorded yet. Run `make toolcalls` on a machine with the models.", ""]
    lines = ["## Tool-call conformance", ""]
    for summary_path in runs:
        run = json.loads(summary_path.read_text())
        meta = run["meta"]
        lines += [f"### {summary_path.parent.name}", "",
                  f"Host `{meta['host']}`, QVAC CLI `{meta.get('qvac_cli', '?')}`, suite `{meta['suite']}` "
                  f"({meta['cases']} cases), greedy sampling, thinking off.", ""]
        cats = [c for c in CATEGORIES if any(c in s["by_category"] for s in run["models"].values())]
        lines.append("| Model | Passed | " + " | ".join(cats) + " | Median latency (s) | Dropped calls |")
        lines.append("|---|---:|" + "---:|" * len(cats) + "---:|---:|")
        for model, s in run["models"].items():
            cells = []
            for c in cats:
                stat = s["by_category"].get(c)
                cells.append(f"{stat['pass']}/{stat['total']}" if stat else "–")
            lines.append(f"| `{model}` | **{s['passed']}/{s['cases']}** | " + " | ".join(cells)
                         + f" | {s['median_latency_s']} | {s['dropped_tool_calls']} |")
        lines += ["", "Failure outcomes:", ""]
        for model, s in run["models"].items():
            failures = {k: v for k, v in sorted(s["outcomes"].items()) if k != "pass"}
            lines.append(f"- `{model}`: " + (", ".join(f"{k} ×{v}" for k, v in failures.items()) or "none"))
        lines.append("")
    return lines


def _smoke_section(results: Path) -> list[str]:
    files = sorted((results / "sdk-smoke").glob("*.json"))
    lines = ["## SDK fresh-install smoke tests", ""]
    if not files:
        return lines + ["No smoke runs recorded yet. Run `make smoke`.", ""]
    for path in files:
        data = json.loads(path.read_text())
        lines += [f"### {path.stem}", "", f"Node `{data['node']}`, Python `{data['python']}`.", "",
                  "| SDK version | JS client | Python client | bare-rpc resolved | Python error |",
                  "|---|---|---|---|---|"]
        for r in data["results"]:
            js, py = r["js"], r["python"]
            err = (py.get("error") or "").replace("|", "\\|")[:120]
            lines.append(f"| {r['version']} | {'PASS' if js.get('ok') else 'FAIL'} | "
                         f"{'PASS' if py.get('ok') else 'FAIL'} | {py.get('bare_rpc', '–')} | {err} |")
        lines.append("")
    return lines


def render(results: Path = ROOT / "results") -> str:
    lines = ["# Results", "",
             "Generated by `make report` from the files in `results/`. Do not edit by hand.", ""]
    lines += _smoke_section(results)
    lines += _toolcall_section(results)
    return "\n".join(lines).rstrip() + "\n"


def write(results: Path = ROOT / "results", target: Path = ROOT / "RESULTS.md") -> Path:
    target.write_text(render(results))
    return target
